package dev.steelcode.core.api.effect;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.steelcode.core.impl.registry.EnchantmentEntry;
import dev.steelcode.core.impl.registry.RegistryContext;
import dev.steelcode.core.impl.util.Refs;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.enchantment.Enchantment;
import org.jetbrains.annotations.ApiStatus;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/**
 * An enchantment, generated by datagen (enchantments are data in 1.21). Effects use the vanilla JSON format.
 * Obtain one with {@code REG.enchantment(name)}.
 * <pre>{@code
 * // Like Sharpness, but stronger against arthropods
 * ResourceKey<Enchantment> VENOM = REG.enchantment("venom")
 *         .supported("#minecraft:enchantable/sword").maxLevel(3).weight(5)
 *         .damageAgainst("#minecraft:sensitive_to_bane_of_arthropods", 2.0, 2.0)
 *         .build();
 *
 * // Attribute: +10% speed per level on boots
 * REG.enchantment("swiftness").supported("#minecraft:enchantable/foot_armor").slots("feet").maxLevel(2)
 *         .attribute("minecraft:generic.movement_speed", 0.1, 0.1, "add_multiplied_base").build();
 * }</pre>
 * Defaults: weapons, weight 5, max level 1, main hand, anvil cost 2. Non-treasure enchantments are added to the
 * enchanting-table, villager-trade and loot tags.
 */
public final class EnchantmentBuilder {

    private final RegistryContext registry;
    private final String name;
    private String supported = "#minecraft:enchantable/weapon";
    private String primary;
    private int weight = 5;
    private int maxLevel = 1;
    private int minBase = 5, minPerLevel = 8, maxBase = 25, maxPerLevel = 8;
    private int anvilCost = 2;
    private final List<String> slots = new ArrayList<>(List.of("mainhand"));
    private String exclusiveSet;
    private boolean treasure;
    private boolean curse;
    private final Map<String, JsonArray> effects = new LinkedHashMap<>();
    private String displayName;

    /** Internal: use {@code REG.enchantment(name)}. */
    @ApiStatus.Internal
    public EnchantmentBuilder(RegistryContext registry, String name) {
        this.registry = registry;
        this.name = Objects.requireNonNull(name);
    }

    /**
     * @param itemsOrTag items that accept it on an anvil, e.g. {@code "#minecraft:enchantable/sword"}
     * @return this builder
     */
    public EnchantmentBuilder supported(String itemsOrTag) { this.supported = itemsOrTag; return this; }
    /**
     * @param itemsOrTag items it appears on in the enchanting table (default: the supported items)
     * @return this builder
     */
    public EnchantmentBuilder primary(String itemsOrTag) { this.primary = itemsOrTag; return this; }
    /**
     * @param weight rarity: 10 common, 5 uncommon, 2 rare, 1 very rare
     * @return this builder
     */
    public EnchantmentBuilder weight(int weight) { this.weight = weight; return this; }
    /**
     * @param level maximum level
     * @return this builder
     */
    public EnchantmentBuilder maxLevel(int level) { this.maxLevel = level; return this; }
    /**
     * @param cost base anvil cost
     * @return this builder
     */
    public EnchantmentBuilder anvilCost(int cost) { this.anvilCost = cost; return this; }

    /**
     * Enchanting-table cost in levels.
     * @param minBase     minimum cost at level I
     * @param minPerLevel minimum cost increase per level
     * @param maxBase     maximum cost at level I
     * @param maxPerLevel maximum cost increase per level
     * @return this builder
     */
    public EnchantmentBuilder cost(int minBase, int minPerLevel, int maxBase, int maxPerLevel) {
        this.minBase = minBase;
        this.minPerLevel = minPerLevel;
        this.maxBase = maxBase;
        this.maxPerLevel = maxPerLevel;
        return this;
    }

    /**
     * @param slots where it works: mainhand, offhand, hand, head, chest, legs, feet, armor, any
     * @return this builder
     */
    public EnchantmentBuilder slots(String... slots) {
        this.slots.clear();
        this.slots.addAll(List.of(slots));
        return this;
    }

    /**
     * @param tag enchantment tag it is incompatible with, e.g. {@code "#minecraft:exclusive_set/damage"}
     * @return this builder
     */
    public EnchantmentBuilder exclusiveWith(String tag) { this.exclusiveSet = tag; return this; }
    /**
     * Only obtainable from chests and trades, not the enchanting table.
     * @return this builder
     */
    public EnchantmentBuilder treasure() { this.treasure = true; return this; }
    /**
     * A curse: red name, cannot be removed with a grindstone (implies {@link #treasure()}).
     * @return this builder
     */
    public EnchantmentBuilder curse() { this.curse = true; this.treasure = true; return this; }
    /**
     * @param english English name instead of the one derived from the id
     * @return this builder
     */
    public EnchantmentBuilder displayName(String english) { this.displayName = english; return this; }

    /**
     * Extra attack damage (Sharpness: 1.0, 0.5).
     * @param base     damage at level I
     * @param perLevel damage added per extra level
     * @return this builder
     */
    public EnchantmentBuilder damage(double base, double perLevel) {
        return damageEffect(base, perLevel, null);
    }

    /**
     * Extra damage against an entity tag (Smite: 2.5, 2.5, {@code "#minecraft:sensitive_to_smite"}).
     * @param entityTag entity type tag
     * @param base      damage at level I
     * @param perLevel  damage added per extra level
     * @return this builder
     */
    public EnchantmentBuilder damageAgainst(String entityTag, double base, double perLevel) {
        return damageEffect(base, perLevel, entityTag);
    }

    private EnchantmentBuilder damageEffect(double base, double perLevel, String entityTag) {
        JsonObject value = linear(base, perLevel);
        JsonObject effect = new JsonObject();
        effect.addProperty("type", "minecraft:add");
        effect.add("value", value);
        JsonObject entry = new JsonObject();
        entry.add("effect", effect);
        if (entityTag != null) {
            JsonObject predicate = new JsonObject();
            predicate.addProperty("type", entityTag);
            JsonObject req = new JsonObject();
            req.addProperty("condition", "minecraft:entity_properties");
            req.addProperty("entity", "this");
            req.add("predicate", predicate);
            entry.add("requirements", req);
        }
        return effect("minecraft:damage", entry);
    }

    /**
     * Modifies an attribute while the item is equipped in one of the {@link #slots}.
     * @param attribute attribute id, e.g. {@code "minecraft:generic.movement_speed"}
     * @param base      amount at level I
     * @param perLevel  amount added per extra level
     * @param operation {@code add_value}, {@code add_multiplied_base} or {@code add_multiplied_total}
     * @return this builder
     */
    public EnchantmentBuilder attribute(String attribute, double base, double perLevel, String operation) {
        JsonObject entry = new JsonObject();
        entry.add("amount", linear(base, perLevel));
        entry.addProperty("attribute", Refs.parse("minecraft", attribute).toString());
        entry.addProperty("id", registry.modId() + ":enchantment." + name);
        entry.addProperty("operation", operation);
        return effect("minecraft:attributes", entry);
    }

    /**
     * Adds any vanilla effect component as raw JSON (see the vanilla enchantments for examples).
     * @param component effect component, e.g. {@code "minecraft:post_attack"}
     * @param entry     one entry of that component's list
     * @return this builder
     */
    public EnchantmentBuilder effect(String component, JsonElement entry) {
        effects.computeIfAbsent(component, k -> new JsonArray()).add(entry);
        return this;
    }

    /**
     * Queues the enchantment JSON, its tags and name.
     * @return the enchantment key, usable with {@code registryAccess().registryOrThrow(Registries.ENCHANTMENT)}
     */
    public ResourceKey<Enchantment> build() {
        ResourceLocation id = ResourceLocation.fromNamespaceAndPath(registry.modId(), name);
        String key = "enchantment." + id.getNamespace() + "." + id.getPath();
        registry.name(key, name, "self", name);
        if (displayName != null) registry.lang("en_us").set(key, displayName);

        JsonObject json = new JsonObject();
        JsonObject description = new JsonObject();
        description.addProperty("translate", key);
        if (curse) description.addProperty("color", "red");
        json.add("description", description);
        json.addProperty("supported_items", supported);
        if (primary != null || !treasure) json.addProperty("primary_items", primary != null ? primary : supported);
        json.addProperty("weight", weight);
        json.addProperty("max_level", maxLevel);
        json.add("min_cost", cost(minBase, minPerLevel));
        json.add("max_cost", cost(maxBase, maxPerLevel));
        json.addProperty("anvil_cost", anvilCost);
        JsonArray s = new JsonArray();
        slots.forEach(s::add);
        json.add("slots", s);
        if (exclusiveSet != null) json.addProperty("exclusive_set", exclusiveSet);
        if (!effects.isEmpty()) {
            JsonObject eff = new JsonObject();
            effects.forEach(eff::add);
            json.add("effects", eff);
        }
        registry.addEnchantment(new EnchantmentEntry(id, () -> json));

        String entry = id.toString();
        String[] tags = curse ? new String[]{"curse", "treasure", "tradeable", "on_random_loot"}
                : treasure ? new String[]{"treasure", "tradeable", "on_random_loot"}
                : new String[]{"in_enchanting_table", "non_treasure", "tradeable", "on_random_loot", "on_traded_equipment",
                "on_mob_spawn_equipment"};
        for (String t : tags) registry.addEnchantmentTag(ResourceLocation.withDefaultNamespace(t), entry);
        return ResourceKey.create(Registries.ENCHANTMENT, id);
    }

    private static JsonObject linear(double base, double perLevel) {
        JsonObject v = new JsonObject();
        v.addProperty("type", "minecraft:linear");
        v.addProperty("base", base);
        v.addProperty("per_level_above_first", perLevel);
        return v;
    }

    private static JsonObject cost(int base, int perLevel) {
        JsonObject c = new JsonObject();
        c.addProperty("base", base);
        c.addProperty("per_level_above_first", perLevel);
        return c;
    }

    private EnchantmentBuilder effect(String component, JsonObject entry) {
        return effect(component, (JsonElement) entry);
    }
}
