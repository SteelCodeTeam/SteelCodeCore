package dev.steelcode.core.content.block;

import com.mojang.serialization.MapCodec;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.block.state.properties.BooleanProperty;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

import java.util.Map;

/**
 * A block with connected textures. It tracks which neighbours are the same block in six boolean properties; the
 * multipart model generated by datagen only draws borders on sides without an identical neighbour.
 * With {@code seeThrough} it behaves like glass (no inner faces, no shading, lets skylight through).
 * Override {@link #connects(BlockState)} to connect to other blocks too.
 */
public class ConnectedBlock extends Block {

    /** The connection property of each direction ({@code true} = an identical neighbour on that side). */
    public static final Map<Direction, BooleanProperty> PROPS = Map.of(
            Direction.NORTH, BlockStateProperties.NORTH, Direction.SOUTH, BlockStateProperties.SOUTH,
            Direction.EAST, BlockStateProperties.EAST, Direction.WEST, BlockStateProperties.WEST,
            Direction.UP, BlockStateProperties.UP, Direction.DOWN, BlockStateProperties.DOWN);

    private final boolean seeThrough;

    /**
     * @param properties block properties
     * @param seeThrough whether it behaves like glass
     */
    public ConnectedBlock(Properties properties, boolean seeThrough) {
        super(properties);
        this.seeThrough = seeThrough;
        BlockState state = stateDefinition.any();
        for (BooleanProperty p : PROPS.values()) state = state.setValue(p, false);
        registerDefaultState(state);
    }

    @Override
    protected MapCodec<? extends Block> codec() {
        return simpleCodec(p -> new ConnectedBlock(p, seeThrough));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        PROPS.values().forEach(builder::add);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        BlockState state = defaultBlockState();
        for (var e : PROPS.entrySet()) {
            state = state.setValue(e.getValue(), connects(context.getLevel().getBlockState(context.getClickedPos().relative(e.getKey()))));
        }
        return state;
    }

    @Override
    protected BlockState updateShape(BlockState state, Direction direction, BlockState neighbor, LevelAccessor level,
                                     BlockPos pos, BlockPos neighborPos) {
        return state.setValue(PROPS.get(direction), connects(neighbor));
    }

    /**
     * @param neighbor the neighbouring state
     * @return whether this block connects to it (default: same block)
     */
    protected boolean connects(BlockState neighbor) {
        return neighbor.is(this);
    }

    @Override
    protected boolean skipRendering(BlockState state, BlockState adjacent, Direction direction) {
        return seeThrough ? adjacent.is(this) : super.skipRendering(state, adjacent, direction);
    }

    @Override
    protected VoxelShape getVisualShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return seeThrough ? Shapes.empty() : super.getVisualShape(state, level, pos, context);
    }

    @Override
    protected float getShadeBrightness(BlockState state, BlockGetter level, BlockPos pos) {
        return seeThrough ? 1.0F : super.getShadeBrightness(state, level, pos);
    }

    @Override
    protected boolean propagatesSkylightDown(BlockState state, BlockGetter level, BlockPos pos) {
        return seeThrough || super.propagatesSkylightDown(state, level, pos);
    }
}
